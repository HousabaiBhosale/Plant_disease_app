function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  localStorage.setItem('language', lang);
  
  // Update language selector dropdowns if present
  const langSelect = document.getElementById('langSelector');
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }
  
  const settingsLang = document.getElementById('settingsLang');
  if (settingsLang && settingsLang.value !== lang) {
    settingsLang.value = lang;
  }

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      // Preserve icons if element starts with an icon
      const icon = el.querySelector('i');
      if (icon) {
        el.innerHTML = '';
        el.appendChild(icon);
        el.appendChild(document.createTextNode(' ' + translations[lang][key]));
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  // Update subtitle based on current page if present
  const subEl = document.getElementById('headerSubtitle');
  if (subEl) {
    const page = window.location.pathname.split('/').pop().replace('.php', '') || 'index';
    let subKey = 'sub_overview';
    if (page === 'analytics') subKey = 'sub_analytics';
    else if (page === 'datasets') subKey = 'sub_datasets';
    else if (page === 'models') subKey = 'sub_models';
    else if (page === 'feedback') subKey = 'sub_feedback';
    else if (page === 'settings') subKey = 'sub_settings';
    
    if (translations[lang][subKey]) {
      subEl.textContent = translations[lang][subKey];
    }
  }
}

function toggleTheme(forceTheme = null) {
  let currentTheme = forceTheme || localStorage.getItem('theme') || 'light';
  if (!forceTheme) {
    currentTheme = currentTheme === 'dark' ? 'light' : 'dark';
  }
  
  localStorage.setItem('theme', currentTheme);
  
  if (currentTheme === 'dark') {
    document.documentElement.setAttribute('data-theme', 'dark');
    document.body.classList.add('dark-theme');
    const themeBtn = document.getElementById('themeBtn');
    if (themeBtn) themeBtn.innerHTML = '<i class="fa-solid fa-sun" style="color: #FBBF24;"></i>';
  } else {
    document.documentElement.removeAttribute('data-theme');
    document.body.classList.remove('dark-theme');
    const themeBtn = document.getElementById('themeBtn');
    if (themeBtn) themeBtn.innerHTML = '<i class="fa-solid fa-moon" style="color: #64748B;"></i>';
  }
  
  const settingsLang = document.getElementById('settingsLang');
  const settingsTheme = document.getElementById('settingsTheme');
  if (settingsTheme && settingsTheme.value !== currentTheme) {
    settingsTheme.value = currentTheme;
  }
}

// Initialize on DOM load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('language') || 'en';
  setLanguage(savedLang);
  
  const savedTheme = localStorage.getItem('theme') || 'light';
  toggleTheme(savedTheme);
});

// Immediately apply theme on script load to prevent white flash
if (localStorage.getItem('theme') === 'dark') {
  document.documentElement.setAttribute('data-theme', 'dark');
}
